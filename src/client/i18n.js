export function translate(lang, key, values = {}) {
  const text = (langPack[lang] || langPack.zh_CN)[key] || langPack.zh_CN[key] || key
  return text.replace(/\{(\w+)\}/g, (match, name) => values[name] == null ? match : String(values[name]))
}
export function localizedContent(record, field, lang) {
  if (!record) return ''
  const suffix = lang === 'zh_HK' ? '_zh_hk' : lang === 'en' ? '_en' : ''
  const value = suffix ? record[field + suffix] : record[field]
  return typeof value === 'string' && value.trim() ? value : (record[field] || '')
}
// Translate server validation messages without leaking Simplified-only UI into other languages.
export function apiError(t, data, fallback = 'requestFailed') {
  if (data?.code && langPack.zh_CN[data.code]) return t(data.code)
  const key = Object.keys(langPack.zh_CN).find(key => langPack.zh_CN[key] === data?.error)
  return t(key || fallback)
}
